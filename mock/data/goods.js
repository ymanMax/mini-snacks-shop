const CATEGORY_NAMES = {
  1: '膨化食品', 2: '糖果巧克力', 3: '坚果炒货', 4: '饼干糕点',
  5: '肉脯卤味', 6: '酒水饮料', 7: '礼盒甄选', 8: '进口零食'
};

const COMMON_TAGS = ['顺丰包邮', '7天无理由', '坏果包赔'];

function poolImg(i) {
  return `/static/mock/u${(i % 8) + 1}.jpg`;
}

function buildGoods() {
  return BASE.map((row, idx) => {
    const [name, brand, catId, price, originalPrice, sales, stock, unit, origin, tags, hot] = row;
    const id = idx + 1;
    const main = `/static/mock/g${String(id).padStart(2, '0')}.jpg`;
    const pics = [main, poolImg(id), poolImg(id + 2), poolImg(id + 4), poolImg(id + 6)];
    const cfg = PACK_SPECS[catId] || PACK_SPECS.default;
    const tastes = Array.isArray(cfg.taste) ? cfg.taste
      : (cfg.taste[catId] || ['原味']);
    const specValues = cfg.spec.map(([label, mult], si) => ({
      label,
      price: round2(price * mult),
      stock: Math.max(10, Math.round(stock / (si === 1 ? 1 : (si === 0 ? 2 : 0.6)))),
      pic: si === 0 ? main : (si === 1 ? main : poolImg(id + 1))
    }));
    const specs = [{
      name: '规格',
      values: specValues
    }, {
      name: '口味',
      values: tastes.map((t) => ({ label: t }))
    }];
    const mergeTags = Array.from(new Set(tags.concat(COMMON_TAGS[0])));
    const hasVideo = VIDEO_IDS.indexOf(id) !== -1;
    return {
      id,
      name,
      brand,
      pic: main,
      pics,
      videoUrl: hasVideo ? (id % 2 === 1 ? '/static/mock/video1.mp4' : '/static/mock/video2.mp4') : '',
      videoCover: main,
      videoIntro: hasVideo ? '店铺实拍短视频，开箱试吃新鲜看得见' : '',
      categoryId: catId,
      categoryName: CATEGORY_NAMES[catId],
      price: round2(price),
      minPrice: round2(price * cfg.spec[0][1]),
      originalPrice: round2(originalPrice),
      memberPrice: round2(price * 0.95),
      numberSells: sales,
      sales,
      stock,
      unit,
      origin,
      tags: mergeTags,
      specs,
      description: `${brand}直供 ${name}，产地${origin}。甄选当季优质原料，${mergeTags.slice(0, 2).join('、')}，` +
        `每一口都是新鲜好味道。规格齐全，居家追剧、办公室分享、走亲访友都合适。`,
      detailImages: [poolImg(id + 3), poolImg(id + 5), poolImg(id + 7)],
      viewCount: sales * 8 + 300,
      collectCount: Math.round(sales / 3),
      isCollect: false,
      hot: hot === 1,
      hotScore: sales + hot * 5000,
      createTime: ''
    };
  });
}

const goods = buildGoods();

